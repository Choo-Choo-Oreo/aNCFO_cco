#!/usr/bin/env python3
"""Fail when a strategic region ID has drifted away from where it used to be.

A region ID is a place, not a number: saves, weather, AI and loc keys all hang
off it. After any province or region edit, every region ID that existed in the
reference commit must still cover (roughly) the same ground. The check rasterises
the region footprint of the reference (git REV: map/provinces.bmp, definition.csv
and strategicregions) and of the working tree, then compares per ID:

  * centroid shift (wrap-aware in x), in pixels
  * IoU of the two footprints
  * land-only regions must be pixel-identical in province membership

Usage (run from anywhere):
  python .global_tools/region_id_drift_check.py <mod_dir> [--ref REV]
        [--max-shift PX] [--min-iou X] [--list N]

Exit code 0 = pass, 1 = at least one violation. Default reference is HEAD, so
run it BEFORE committing; use --ref <published sha> to measure against a release.
New IDs (absent from the reference) are listed but not judged.
Generated by claude.
"""
from __future__ import annotations

import io
import re
import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image

Image.MAX_IMAGE_PIXELS = None
MAX_SHIFT = 150.0
MIN_IOU = 0.30
LIST_N = 25


def git_show(mod: Path, rev: str, rel: str) -> bytes:
    return subprocess.check_output(["git", "-C", str(mod), "show", f"{rev}:{rel}"])


def parse_definition(raw: str):
    col2id, ty = {}, {}
    for ln in raw.splitlines():
        p = ln.strip().split(";")
        if len(p) >= 5 and p[0].isdigit():
            col2id[(int(p[1]) << 16) | (int(p[2]) << 8) | int(p[3])] = int(p[0])
            ty[int(p[0])] = p[4]
    return col2id, ty


def province_ids(img_bytes_or_path, col2id):
    img = Image.open(io.BytesIO(img_bytes_or_path) if isinstance(img_bytes_or_path, bytes) else img_bytes_or_path).convert("RGB")
    a = np.asarray(img)
    pk = (a[..., 0].astype(np.uint32) << 16) | (a[..., 1].astype(np.uint32) << 8) | a[..., 2]
    cs = np.array(sorted(col2id))
    ci = np.array([col2id[c] for c in cs], np.int32)
    return ci[np.searchsorted(cs, pk)]


def parse_regions(texts):
    regs = {}
    for t in texts:
        m = re.search(r"\bid\s*=\s*(\d+)", t)
        p = re.search(r"provinces\s*=\s*\{([^}]*)\}", t)
        if m and p:
            regs[int(m.group(1))] = [int(v) for v in p.group(1).split()]
    return regs


def ref_regions(mod: Path, rev: str):
    names = subprocess.check_output(["git", "-C", str(mod), "ls-tree", "-z", "--name-only", rev, "map/strategicregions/"], text=True).split("\0")
    return parse_regions(git_show(mod, rev, n).decode("utf-8-sig", "ignore") for n in names if n.endswith(".txt"))


def region_raster(ID, regs, n):
    lut = np.zeros(n, np.int32)
    for r, l in regs.items():
        for p in l:
            lut[p] = r
    return lut[ID]


def stats(R, rid, W):
    ys, xs = np.nonzero(R == rid)
    if not len(xs):
        return None
    ang = xs / W * 2 * np.pi
    cx = (np.arctan2(np.sin(ang).mean(), np.cos(ang).mean()) % (2 * np.pi)) / (2 * np.pi) * W
    return cx, ys.mean(), len(xs)


def main(argv):
    if not argv or argv[0].startswith("--"):
        print(__doc__)
        return 2
    mod = Path(argv[0]).resolve()
    opt = {"--ref": "HEAD", "--max-shift": MAX_SHIFT, "--min-iou": MIN_IOU, "--list": LIST_N}
    i = 1
    while i < len(argv):
        if argv[i] in opt and i + 1 < len(argv):
            opt[argv[i]] = type(opt[argv[i]])(argv[i + 1]); i += 2
        else:
            i += 1
    rev = opt["--ref"]
    c_old, ty_old = parse_definition(git_show(mod, rev, "map/definition.csv").decode("utf-8", "ignore"))
    c_new, ty_new = parse_definition((mod / "map/definition.csv").read_text(encoding="utf-8", errors="ignore"))
    old_id = province_ids(git_show(mod, rev, "map/provinces.bmp"), c_old)
    new_id = province_ids(mod / "map/provinces.bmp", c_new)
    H, W = new_id.shape
    regs_old = ref_regions(mod, rev)
    regs_new = parse_regions(p.read_text(encoding="utf-8-sig", errors="ignore") for p in (mod / "map/strategicregions").glob("*.txt"))
    Ro = region_raster(old_id, regs_old, max(ty_old) + 1)
    Rn = region_raster(new_id, regs_new, max(ty_new) + 1)
    rows, bad = [], []
    for rid in sorted(regs_old):
        so = stats(Ro, rid, W)
        if so is None:
            continue
        sn = stats(Rn, rid, W)
        landonly = all(ty_old.get(p) != "sea" for p in regs_old[rid])
        if sn is None:
            bad.append((rid, "ID has no provinces any more", 9e9, 0.0)); continue
        dx = abs(so[0] - sn[0]); dx = min(dx, W - dx)
        shift = float(np.hypot(dx, so[1] - sn[1]))
        inter = int(((Ro == rid) & (Rn == rid)).sum()); uni = so[2] + sn[2] - inter
        iou = inter / uni
        rows.append((rid, shift, iou, landonly))
        if landonly and set(regs_old[rid]) != set(regs_new.get(rid, [])):
            land_old = {p for p in regs_old[rid]}; land_new = set(regs_new.get(rid, []))
            if land_old != land_new:
                bad.append((rid, "land-only region membership changed", shift, iou))
        if shift > opt["--max-shift"] or iou < opt["--min-iou"]:
            bad.append((rid, f"drift: shift {shift:.0f}px (max {opt['--max-shift']:.0f}), IoU {iou:.2f} (min {opt['--min-iou']})", shift, iou))
    new_ids = sorted(set(regs_new) - set(regs_old))
    print(f"reference {rev}: {len(regs_old)} IDs | working tree: {len(regs_new)} IDs | new IDs not judged: {len(new_ids)}")
    worst = sorted(rows, key=lambda r: -r[1])[: int(opt["--list"])]
    print("largest centroid shifts (ID, px, IoU):", ", ".join(f"{r[0]}:{r[1]:.0f}px/{r[2]:.2f}" for r in worst))
    seen = set()
    for rid, why, shift, iou in bad:
        if (rid, why) in seen: continue
        seen.add((rid, why)); print("FAIL region", rid, "-", why)
    print("PASS" if not bad else f"FAIL: {len({b[0] for b in bad})} region IDs violate the drift limit")
    return 0 if not bad else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
