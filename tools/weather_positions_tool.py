#!/usr/bin/env python3
"""weather_positions_tool.py - audit / regenerate map/weatherpositions.txt for any HoI4 mod.

File format (one line per point):  region_id;x;y;z;size      e.g.  12;3341.00;10.00;1234.00;big
  x,z are map coordinates, pixel = (x, H-1-round(z)) in provinces.bmp; y is height.
The engine does not validate the file; a point outside its region only moves weather effects
to the wrong place, and a region with no points gets no local weather effects.

audit      report points that fall outside their region and regions with too few points
generate   build a covering set: every pixel of a region lies within --radius px of one of its points
           (farthest-point sampling), at least --min points per region, at most --max.
           Small regions (< --small-area px) use size "small", the rest "big".

Usage (from a mod root):
  python tools/weather_positions_tool.py audit
  python tools/weather_positions_tool.py generate --out weatherpositions.new.txt [--png preview.png]
  python tools/weather_positions_tool.py generate --apply          # overwrite map/weatherpositions.txt
Options: --mod PATH  --radius 90  --min 2  --max 14  --small-area 2500
Reads only provinces.bmp, definition.csv and map/strategicregions/*.txt.  Generated by claude.
"""
import argparse, glob, os, re, sys, collections
import numpy as np
from PIL import Image

Image.MAX_IMAGE_PIXELS = None


def load(mod):
    d = {}
    for ln in open(os.path.join(mod, "map/definition.csv"), encoding="latin1"):
        p = ln.strip().split(";")
        if len(p) >= 5 and p[0].isdigit():
            d[(int(p[1]) << 16) | (int(p[2]) << 8) | int(p[3])] = int(p[0])
    cs = np.array(sorted(d)); ci = np.array([d[c] for c in cs], np.int32)
    a = np.asarray(Image.open(os.path.join(mod, "map/provinces.bmp")).convert("RGB"))
    P = (a[..., 0].astype(np.uint32) << 16) | (a[..., 1].astype(np.uint32) << 8) | a[..., 2]
    PID = ci[np.searchsorted(cs, P)]
    lut = np.zeros(int(PID.max()) + 1, np.int32)
    for f in glob.glob(os.path.join(mod, "map/strategicregions/*.txt")):
        t = open(f, encoding="utf-8-sig", errors="ignore").read()
        m = re.search(r"\bid\s*=\s*(\d+)", t); p = re.search(r"provinces\s*=\s*\{([^}]*)\}", t)
        if m and p:
            for v in p.group(1).split():
                if int(v) < len(lut): lut[int(v)] = int(m.group(1))
    return lut[PID]


def read_points(path):
    out = []
    if os.path.exists(path):
        for l in open(path, encoding="latin1"):
            f = l.strip().split(";")
            if len(f) >= 5 and f[0].isdigit(): out.append((int(f[0]), float(f[1]), float(f[2]), float(f[3]), f[4]))
    return out


def audit(R, pts):
    H, W = R.shape; bad = []; cnt = collections.Counter()
    for rid, x, y, z, s in pts:
        cnt[rid] += 1
        r, c = H - 1 - int(round(z)), int(round(x)) % W
        if not (0 <= r < H) or R[r, c] != rid: bad.append((rid, x, z))
    ids = sorted(set(np.unique(R).tolist()) - {0})
    return bad, cnt, [i for i in ids if cnt[i] == 0]


def wrap_d2(ys, xs, y0, x0, W):
    dx = np.abs(xs - x0); dx = np.minimum(dx, W - dx)
    return (ys - y0) ** 2 + dx ** 2


def generate(R, radius, kmin, kmax, small_area, stride=3):
    H, W = R.shape; out = []; K = {}
    for rid in sorted(set(np.unique(R).tolist()) - {0}):
        ys, xs = np.nonzero(R == rid)
        area = len(ys)
        sel = np.arange(0, area, max(1, stride * stride // 2))     # thinned candidate set
        cy, cx = ys[sel], xs[sel]
        # start: pixel nearest the (wrap-aware) centroid
        ang = xs / W * 2 * np.pi
        mx = (np.arctan2(np.sin(ang).mean(), np.cos(ang).mean()) % (2 * np.pi)) / (2 * np.pi) * W
        i0 = int(np.argmin(wrap_d2(cy, cx, ys.mean(), mx, W)))
        chosen = [i0]; dist = wrap_d2(cy, cx, cy[i0], cx[i0], W).astype(np.float64)
        while len(chosen) < kmax:
            j = int(np.argmax(dist))
            if len(chosen) >= kmin and dist[j] <= radius ** 2: break
            chosen.append(j); dist = np.minimum(dist, wrap_d2(cy, cx, cy[j], cx[j], W))
        size = "big" if area >= small_area else "small"
        for j in chosen:
            out.append((rid, float(cx[j]), 10.0, float(H - 1 - cy[j]), size))
        K[rid] = len(chosen)
    return out, K


def write(path, pts):
    open(path, "w", encoding="latin1", newline="").write(
        "\n".join("%d;%.2f;%.2f;%.2f;%s" % p for p in pts))


def preview(R, pts, png):
    H, W = R.shape; rng = np.random.RandomState(5); pal = rng.randint(90, 235, (int(R.max()) + 1, 3)).astype(np.uint8)
    img = pal[R]; img[R == 0] = 255
    for rid, x, y, z, s in pts:
        r, c = H - 1 - int(round(z)), int(round(x)) % W
        n = 4 if s == "big" else 2
        img[max(0, r - n):r + n + 1, max(0, c - n):c + n + 1] = (0, 0, 0)
    Image.fromarray(img).resize((W // 2, H // 2), Image.NEAREST).save(png)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["audit", "generate"]); ap.add_argument("--mod", default=".")
    ap.add_argument("--radius", type=float, default=90); ap.add_argument("--min", type=int, default=2)
    ap.add_argument("--max", type=int, default=14); ap.add_argument("--small-area", type=int, default=2500)
    ap.add_argument("--out", default=""); ap.add_argument("--png", default=""); ap.add_argument("--apply", action="store_true")
    a = ap.parse_args(); mod = os.path.abspath(a.mod)
    R = load(mod); path = os.path.join(mod, "map/weatherpositions.txt"); pts = read_points(path)
    bad, cnt, none = audit(R, pts)
    print("current file: %d points, %d outside their region, %d regions with no point" % (len(pts), len(bad), len(none)))
    if a.cmd == "generate":
        new, K = generate(R, a.radius, a.min, a.max, a.small_area)
        b2, c2, n2 = audit(R, new)
        print("generated: %d points for %d regions (min %d, max %d per region); outside: %d; uncovered regions: %d" % (
            len(new), len(K), min(K.values()), max(K.values()), len(b2), len(n2)))
        hist = collections.Counter(K.values()); print("points per region:", dict(sorted(hist.items())))
        out = path if a.apply else (a.out or os.path.join(mod, "weatherpositions.new.txt"))
        write(out, new); print("written:", out)
        if a.png: preview(R, new, a.png)
    return 0


if __name__ == "__main__":
    sys.exit(main())
